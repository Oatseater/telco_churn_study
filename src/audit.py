"""Data audit: checks the raw file before anything is changed.

Every count here is computed from the raw CSV and written to
reports/audit_report.md so the cleaning decisions in DECISIONS.md can be traced
back to evidence.
"""
from __future__ import annotations

import pandas as pd

from src import config


class SchemaError(RuntimeError):
    """Raised when the raw file is missing or does not match the expected schema."""


def load_raw(path=config.RAW_CSV) -> pd.DataFrame:
    if not path.exists():
        raise SchemaError(
            f"Raw data file not found at {path}. Place the public Telco Customer "
            "Churn CSV in data/raw/ and re-run."
        )
    # Read everything as text first so type problems are visible, not silently coerced.
    df = pd.read_csv(path, dtype=str, keep_default_na=False)
    cols = list(df.columns)
    if cols != config.EXPECTED_COLUMNS:
        missing = sorted(set(config.EXPECTED_COLUMNS) - set(cols))
        extra = sorted(set(cols) - set(config.EXPECTED_COLUMNS))
        raise SchemaError(
            "Raw file columns differ from the expected Telco schema. "
            f"Missing: {missing or 'none'}. Unexpected: {extra or 'none'}. "
            "Stopping rather than guessing."
        )
    return df


def _iqr_outliers(s: pd.Series) -> dict:
    q1, q3 = s.quantile(0.25), s.quantile(0.75)
    iqr = q3 - q1
    lo, hi = q1 - 1.5 * iqr, q3 + 1.5 * iqr
    n_out = int(((s < lo) | (s > hi)).sum())
    return {"q1": float(q1), "q3": float(q3), "lower_fence": float(lo),
            "upper_fence": float(hi), "n_outliers": n_out,
            "min": float(s.min()), "max": float(s.max())}


def run_audit(raw: pd.DataFrame) -> dict:
    """Return a dictionary of audit findings computed from the raw text frame."""
    out: dict = {"n_rows": int(len(raw)), "n_columns": int(raw.shape[1])}

    # Nulls: true NaN (none, since read as text) and blank / whitespace-only strings.
    blank = raw.apply(lambda c: c.str.strip().eq("")).sum()
    out["blank_by_column"] = {k: int(v) for k, v in blank.items() if v > 0}
    out["nan_total"] = int(raw.isna().sum().sum())

    # Duplicates
    out["duplicate_ids"] = int(raw["customerID"].duplicated().sum())
    out["duplicate_rows_excl_id"] = int(raw.drop(columns="customerID").duplicated().sum())
    out["duplicate_rows_full"] = int(raw.duplicated().sum())

    # Type issues: columns that should be numeric
    type_issues = {}
    for col in ["SeniorCitizen", "tenure", "MonthlyCharges", "TotalCharges"]:
        coerced = pd.to_numeric(raw[col], errors="coerce")
        bad = raw.loc[coerced.isna(), col]
        type_issues[col] = {"n_non_numeric": int(len(bad)),
                            "examples": sorted(set(repr(v) for v in bad))[:3]}
    out["type_issues"] = type_issues

    # Blank TotalCharges: who are they?
    tc_blank = raw["TotalCharges"].str.strip().eq("")
    out["total_charges_blank"] = int(tc_blank.sum())
    out["total_charges_blank_tenures"] = sorted(
        set(int(t) for t in raw.loc[tc_blank, "tenure"]))
    out["tenure_zero_rows"] = int((raw["tenure"].astype(int) == 0).sum())

    # Categorical levels
    cats = {}
    for col in raw.columns:
        if col in ("customerID", "tenure", "MonthlyCharges", "TotalCharges"):
            continue
        cats[col] = sorted(raw[col].unique().tolist())
    out["categorical_levels"] = cats

    # Leading / trailing whitespace in any text cell (excluding blanks counted above)
    ws = raw.apply(lambda c: (c != c.str.strip()) & c.str.strip().ne("")).sum()
    out["whitespace_cells"] = int(ws.sum())

    # Outliers (IQR rule) on numeric columns
    num = pd.DataFrame({
        "tenure": pd.to_numeric(raw["tenure"]),
        "MonthlyCharges": pd.to_numeric(raw["MonthlyCharges"]),
        "TotalCharges": pd.to_numeric(raw["TotalCharges"], errors="coerce"),
    })
    out["outliers_iqr"] = {c: _iqr_outliers(num[c].dropna()) for c in num.columns}

    # Internal consistency: TotalCharges should be roughly tenure x MonthlyCharges.
    valid = num.dropna()
    valid = valid[valid["tenure"] > 0]
    ratio = valid["TotalCharges"] / (valid["tenure"] * valid["MonthlyCharges"])
    out["total_vs_expected_ratio"] = {
        "median": float(ratio.median()),
        "p01": float(ratio.quantile(0.01)),
        "p99": float(ratio.quantile(0.99)),
        "share_within_20pct": float(((ratio > 0.8) & (ratio < 1.2)).mean()),
    }

    # Target balance
    out["churn_yes"] = int((raw["Churn"] == "Yes").sum())
    out["churn_share"] = float((raw["Churn"] == "Yes").mean())
    return out


def write_audit_report(audit: dict, path=config.AUDIT_REPORT) -> None:
    lines = [
        "# Data audit report",
        "",
        "Generated by `run_pipeline.py` from the raw CSV. Do not edit by hand.",
        "",
        f"- Rows: {audit['n_rows']:,}; columns: {audit['n_columns']}",
        f"- True NaN cells: {audit['nan_total']:,}",
        f"- Blank or whitespace-only cells by column: {audit['blank_by_column'] or 'none'}",
        f"- Duplicate customer IDs: {audit['duplicate_ids']:,}",
        f"- Rows identical on every column except customer ID: {audit['duplicate_rows_excl_id']:,}",
        f"- Fully duplicated rows: {audit['duplicate_rows_full']:,}",
        f"- Text cells with leading or trailing whitespace: {audit['whitespace_cells']:,}",
        f"- Customers with tenure 0: {audit['tenure_zero_rows']:,}",
        f"- Blank TotalCharges: {audit['total_charges_blank']:,}, all at tenure "
        f"{audit['total_charges_blank_tenures']}",
        f"- Churned customers: {audit['churn_yes']:,} ({audit['churn_share']:.1%})",
        "",
        "## Type issues (values that do not parse as numbers)",
        "",
        "| Column | Non-numeric values | Examples |",
        "|---|---:|---|",
    ]
    for col, info in audit["type_issues"].items():
        lines.append(f"| {col} | {info['n_non_numeric']:,} | {', '.join(info['examples']) or '-'} |")
    lines += [
        "",
        "## Outliers (1.5 x IQR rule)",
        "",
        "| Column | Min | Q1 | Q3 | Max | Lower fence | Upper fence | Outliers |",
        "|---|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for col, o in audit["outliers_iqr"].items():
        lines.append(
            f"| {col} | {o['min']:,.2f} | {o['q1']:,.2f} | {o['q3']:,.2f} | {o['max']:,.2f} | "
            f"{o['lower_fence']:,.2f} | {o['upper_fence']:,.2f} | {o['n_outliers']:,} |")
    r = audit["total_vs_expected_ratio"]
    lines += [
        "",
        "## Consistency: TotalCharges vs tenure x MonthlyCharges",
        "",
        f"- Median ratio: {r['median']:.3f}; 1st to 99th percentile: {r['p01']:.3f} to {r['p99']:.3f}",
        f"- Share of customers within +/-20% of the expected total: {r['share_within_20pct']:.1%}",
        "",
        "## Categorical levels",
        "",
    ]
    for col, levels in audit["categorical_levels"].items():
        lines.append(f"- {col}: {', '.join(map(str, levels))}")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
